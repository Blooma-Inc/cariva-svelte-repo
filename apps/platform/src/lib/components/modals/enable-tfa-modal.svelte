<script lang="ts" module>
	import { z } from 'zod';

	export const enableTFASchema = z.object({
		code: z.string({ error: 'Code is required' })
	});
	export type EnableTFASchemaType = z.infer<typeof enableTFASchema>;
</script>

<script lang="ts">
	import DialogModal from '$lib/atoms/modals/dialogModal.svelte';
	import { AppModals } from '$lib/store/app/modal-types';
	import { stores } from '$lib/store/index.svelte';
	import { Button } from '@cariva/ui/components/ui/button/index.js';
	import { DialogContent, DialogFooter } from '@cariva/ui/components/ui/dialog/index.js';
	import { Heading, Paragraph } from '@cariva/ui/components/ui/typography/index.js';
	import { InputField } from '@cariva/ui/components/form-inputs/input-field/index.js';
	import { FormField } from '@cariva/ui/components/ui/form/index.js';
	import { superForm } from 'sveltekit-superforms';
	import { zod4Client } from 'sveltekit-superforms/adapters';
	import { useQueryClient } from '@tanstack/svelte-query';
	import { TFA } from '$lib/constants/api';

	const { AppStore, AuthStore } = stores;
	const queryClient = useQueryClient();

	const cbFn = () => {
		queryClient.invalidateQueries({ predicate: (query) => query.queryKey[0] == TFA.GET_2FA });
	};

	const form = superForm(
		{ code: '' },
		{
			SPA: true,
			resetForm: false,
			validators: zod4Client(enableTFASchema),
			onUpdate: async ({ form }) => {
				if (form.valid) {
					await AuthStore.enable2FA(form.data, cbFn);
				}
			}
		}
	);

	const { form: formData, enhance } = form;

	const handleClose = () => {
		AppStore.toggleModals({ name: AppModals.ENABLE_TFA_MODAL, open: false });
	};
</script>

<DialogModal isOpen={AppStore.isOpen.ENABLE_TFA_MODAL} closeModal={handleClose}>
	<DialogContent
		showCloseButton={false}
		onEscapeKeydown={(e) => e.preventDefault()}
		onInteractOutside={(e) => e.preventDefault()}
	>
		<div class="flex flex-col items-center justify-center gap-3 rounded-xl">
			<div class="text-center">
				<Heading level="h2" class="text-primary!">Verify your setup</Heading>
				<Paragraph size="sm" class=" text-neutral-500!"
					>Enter the verification code generated by your authenticator app.</Paragraph
				>
			</div>
			<form id="enable-tfa-form" use:enhance>
				<fieldset>
					<FormField {form} name="code">
						<InputField
							label=""
							placeholder="Enter 6-digit code"
							bind:value={$formData.code}
							required
							description="Code refreshes every 30 seconds"
						/>
					</FormField>
				</fieldset>
			</form>

			<DialogFooter class="">
				<Button
					type="submit"
					size="lg"
					form="enable-tfa-form"
					disabled={AuthStore.loaders.isEnablingTFA}>Enable 2FA</Button
				>
			</DialogFooter>
		</div>
	</DialogContent>
</DialogModal>
